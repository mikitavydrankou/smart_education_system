import { test, expect } from '@playwright/test'
import { sourceText, richCourseFixture as courseFixture } from '../material-fixture'
import { defaultProfile } from '../../lib/material'

test('own material becomes a selected course with adaptive retry, persistence and results', async ({ page }) => {
  await page.route('**/api/material', async route => {
    const input = route.request().postDataJSON()
    expect(input.text).toContain('Fotosynteza')
    expect(input.profile.goal).toBe('exam')
    await route.fulfill({ json: { course: courseFixture } })
  })
  await page.goto('/workspace')
  await page.getByLabel('Materiał źródłowy', { exact: true }).fill(sourceText)
  await page.getByLabel('Cel nauki').selectOption('exam')
  await page.getByRole('button', { name: 'Przygotuj moją lekcję' }).click()
  await expect(page.getByRole('heading', { name: 'Twoja mapa nauki' })).toBeVisible()
  await page.getByRole('checkbox', { name: /Substraty/ }).uncheck()
  await page.getByRole('button', { name: 'Zacznij naukę' }).click()
  await page.getByRole('button', { name: 'Schemat', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Krok po kroku' })).toBeVisible()
  await page.getByRole('button', { name: 'Audio', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Przygotuj nagranie' })).toBeVisible()
  await page.getByRole('button', { name: 'Tekst', exact: true }).click()
  await page.getByText('Zobacz fragment źródła').click()
  await expect(page.getByText('Fotosynteza zachodzi w chloroplastach.', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Sprawdź zrozumienie' }).click()
  await page.getByRole('radio').nth(2).check()
  await page.reload()
  await expect(page.getByRole('radio').nth(2)).toBeChecked()
  await page.getByRole('button', { name: 'Sprawdź odpowiedź' }).click()
  await expect(page.getByText('Przyjrzyjmy się temu jeszcze raz.')).toBeVisible()
  await page.getByRole('button', { name: 'Spróbuj w nowym zadaniu' }).click()
  await page.getByRole('radio').nth(1).check()
  await page.getByRole('button', { name: 'Sprawdź odpowiedź' }).click()
  await page.reload()
  await expect(page.getByText('Dodatkowe wyjaśnienie pomogło.')).toBeVisible()
  await page.getByRole('button', { name: 'Następny temat' }).click()
  await expect(page.getByRole('button', { name: 'Schemat', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Sprawdź zrozumienie' }).click()
  await page.getByRole('radio').first().check()
  await page.getByRole('button', { name: 'Sprawdź odpowiedź' }).click()
  await page.getByRole('button', { name: 'Zobacz podsumowanie' }).click()
  await expect(page.getByText('Poprawnie od razu: 1 z 2. Po dodatkowym wyjaśnieniu: 1.')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Twoje podsumowanie' })).toBeVisible()
  await page.getByRole('button', { name: 'Powtórz tę lekcję' }).click()
  await expect(page.getByRole('heading', { name: 'Twoja mapa nauki' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('text import and failed generation preserve the source without a fictional course', async ({ page, request }) => {
  await page.route('**/api/material', route => route.fulfill({ status: 503, json: { error: 'Usługa AI jest niedostępna.' } }))
  await page.goto('/workspace')
  await page.getByLabel('Wybierz plik').setInputFiles({ name: 'biologia.txt', mimeType: 'text/plain', buffer: Buffer.from(sourceText) })
  await expect(page.getByLabel('Materiał źródłowy', { exact: true })).toHaveValue(sourceText)
  await page.getByRole('button', { name: 'Przygotuj moją lekcję' }).click()
  await expect(page.getByRole('alert').filter({ hasText: /Usługa AI|Nie można/ })).toContainText('Usługa AI jest niedostępna.')
  await page.reload()
  await expect(page.getByLabel('Materiał źródłowy', { exact: true })).toHaveValue(sourceText)
  const invalid = await request.post('/api/material', { data: { text: 'too short', profile: {} } })
  expect(invalid.status()).toBe(400)
  const origin = await request.post('/api/material', { headers: { origin: 'https://other.example' }, data: { text: sourceText } })
  expect(origin.status()).toBe(403)
  const unavailable = await request.post('/api/material', { data: { text: sourceText, profile: defaultProfile } })
  expect(unavailable.status()).toBe(503)
  expect(await unavailable.json()).not.toHaveProperty('course')
})

test('DOCX and PDF extraction work locally and invalid documents produce Polish errors', async ({ page }) => {
  await page.goto('/workspace')
  for (const file of ['tests/fixtures/material.docx', 'tests/fixtures/material.pdf']) {
    await page.getByLabel('Wybierz plik').setInputFiles(file)
    await expect(page.getByLabel('Materiał źródłowy', { exact: true })).toHaveValue(/Fotosynteza zachodzi w chloroplastach/)
    await expect(page.getByLabel('Nazwa materiału')).toHaveValue(file.split('/').pop()!)
  }
  await page.getByLabel('Wybierz plik').setInputFiles({ name: 'broken.docx', mimeType: 'application/octet-stream', buffer: Buffer.from('not a zip') })
  await expect(page.getByRole('alert').filter({ hasText: /Usługa AI|Nie można/ })).toContainText('Nie można odczytać dokumentu.')
  await expect(page.getByLabel('Materiał źródłowy', { exact: true })).toHaveValue(/Fotosynteza/)
})

test('incorrect retry yields persistent review results without a third attempt', async ({ page }) => {
  await page.route('**/api/material', route => route.fulfill({ json: { course: courseFixture } }))
  await page.goto('/workspace')
  await page.getByLabel('Materiał źródłowy', { exact: true }).fill(sourceText)
  await page.getByRole('button', { name: 'Praktyka', exact: true }).click()
  await page.getByRole('button', { name: 'Przygotuj moją lekcję' }).click()
  await page.getByRole('checkbox', { name: /Chlorofil/ }).uncheck()
  await page.getByRole('checkbox', { name: /Substraty/ }).uncheck()
  await page.reload()
  await expect(page.getByRole('checkbox', { name: /Chlorofil/ })).not.toBeChecked()
  await page.getByRole('button', { name: 'Zacznij naukę' }).click()
  await page.getByRole('button', { name: 'Sprawdź zrozumienie' }).click()
  await page.getByRole('radio').nth(2).check()
  await page.getByRole('button', { name: 'Sprawdź odpowiedź' }).click()
  await page.getByRole('button', { name: 'Spróbuj w nowym zadaniu' }).click()
  await page.getByRole('radio').first().check()
  await page.getByRole('button', { name: 'Sprawdź odpowiedź' }).click()
  await expect(page.getByText('Ten temat warto jeszcze powtórzyć.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Spróbuj w nowym zadaniu' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Zobacz podsumowanie' }).click()
  await page.reload()
  await expect(page.getByText('Poprawnie od razu: 0 z 1. Po dodatkowym wyjaśnieniu: 0.')).toBeVisible()
  await expect(page.getByText('Warto powtórzyć: Chloroplasty.')).toBeVisible()
})

